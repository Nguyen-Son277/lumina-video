import { expect, test } from '@playwright/test'
import { BASE, signUpFresh } from './helpers/auth'

test.beforeEach(async ({ page }) => { await signUpFresh(page) })
async function preset(page: import('@playwright/test').Page) {
  const response = await page.request.post(`${BASE}/api/providers`, { data: { name: 'Higgsfield', baseUrl: 'https://api.higgsfield.ai', apiKey: 'test-hf-id:test-hf-secret', authScheme: 'higgsfield' } })
  expect(response.status()).toBe(201)
  await page.goto(`${BASE}/?page=quick`)
  await page.locator('.mode-tabs button').nth(1).click()
}
test('Higgsfield provider accepts one complete credential field', async ({ page }) => {
  await page.goto(`${BASE}/?page=settings`)
  await page.getByRole('button', { name: 'API & Models', exact: true }).click()
  await page.getByRole('button', { name: 'Thêm provider', exact: true }).first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Giao thức nhà cung cấp').selectOption('higgsfield')
  const credential = dialog.getByLabel('Khóa API Higgsfield', { exact: true })
  await expect(credential).toHaveCount(1)
  await expect(dialog.getByLabel('Higgsfield Key Secret', { exact: true })).toHaveCount(0)
  await credential.fill('bad-format')
  await expect(dialog.getByRole('button', { name: 'Lưu provider', exact: true })).toBeDisabled()
  await credential.fill('  fake-hf-id:fake-hf-secret  ')
  const response = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/api/providers'))
  await dialog.getByRole('button', { name: 'Lưu provider', exact: true }).click()
  const result = await response
  expect(result.status()).toBe(201)
  expect(result.request().postDataJSON().apiKey).toBe('fake-hf-id:fake-hf-secret')
  expect(JSON.stringify(await result.json())).not.toContain('fake-hf-id:fake-hf-secret')
})
test('saved provider remains successful when model refresh fails', async ({ page }) => {
  await page.goto(`${BASE}/?page=settings`)
  await page.getByRole('button', { name: 'API & Models', exact: true }).click()
  await page.getByRole('button', { name: 'Thêm provider', exact: true }).first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Giao thức nhà cung cấp').selectOption('higgsfield')
  await dialog.getByLabel('Khóa API Higgsfield', { exact: true }).fill('fake-refresh-id:fake-refresh-secret')
  await page.route('**/api/models', route => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: { code: 'INTERNAL_ERROR', message: 'Refresh failed' } }) }))
  await dialog.getByRole('button', { name: 'Lưu provider', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('status').filter({ hasText: 'Provider đã lưu.' })).toBeVisible()
  expect((await page.request.get(`${BASE}/api/providers`).then(r => r.json())).providers).toHaveLength(1)
})
test('Higgsfield text controls send exact schema and switching modes clears text-only fields', async ({ page }) => {
  await preset(page)
  await expect(page.getByRole('button', { name: 'Tạo từ văn bản', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Độ phân giải', exact: true }).selectOption('1080p')
  await page.getByRole('combobox', { name: 'Tỷ lệ khung hình', exact: true }).selectOption('9:16')
  await page.getByRole('combobox', { name: 'Định dạng đầu ra', exact: true }).selectOption('mov')
  await page.getByPlaceholder('Mô tả điều bạn muốn tạo...').fill('Một chiếc thuyền trên hồ')
  const request = page.waitForRequest(r => r.method() === 'POST' && r.url().endsWith('/api/generations'))
  await page.locator('.generate-button').click()
  expect((await request).postDataJSON().params).toMatchObject({ mode: 'text', duration: 5, resolution: '1080p', aspectRatio: '9:16', outputFormat: 'mov', generateAudio: true })
  await page.getByRole('button', { name: 'Tạo từ ảnh', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Định dạng đầu ra', exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Ảnh đầu (bắt buộc)')).toBeVisible()
})
test('image mode uploads frame and creates video without prompt', async ({ page }) => {
  await preset(page)
  await page.getByRole('button', { name: 'Tạo từ ảnh', exact: true }).click()
  await page.getByLabel('Ảnh đầu (bắt buộc)').setInputFiles({ name: 'frame.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/l9sAAAAASUVORK5CYII=', 'base64') })
  await expect(page.getByRole('button', { name: 'Gỡ ảnh', exact: true })).toBeVisible()
  const response = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/api/generations'))
  await page.locator('.generate-button').click()
  const result = await response
  expect(result.status()).toBe(202)
  const job = (await result.json()).generation
  expect(job.params).toMatchObject({ mode: 'image' })
  expect(job.params.imageUploadId).toBeTruthy()
  expect(job.params.aspectRatio).toBeUndefined()
  expect(job.params.outputFormat).toBeUndefined()
})
