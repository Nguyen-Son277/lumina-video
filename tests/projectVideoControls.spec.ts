import { test, expect } from '@playwright/test'
import { BASE, seedProvider, seedModel, signUpFresh, waitForGeneration } from './helpers/auth'

async function openScene(page: import('@playwright/test').Page) {
  await page.goto(BASE)
  await page.getByRole('button', { name: 'Tạo dự án', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Tạo dự án' })
  await dialog.getByLabel('Tên dự án').fill('Scene video regression')
  await dialog.getByRole('button', { name: 'Lưu dự án' }).click()
  await page.getByRole('tab', { name: 'Cảnh video', exact: true }).click()
  await page.getByRole('button', { name: 'Thêm cảnh', exact: true }).click()
  return page.locator('.project-scene-editor')
}

test('scene provider filtering, protocol defaults, validation and full mock generation', async ({ page }) => {
  await signUpFresh(page)
  const a = await seedProvider(page, { name: 'Provider A' })
  const b = await seedProvider(page, { name: 'Provider B' })
  const openai = await seedModel(page, a, { modelId: 'video-a', displayName: 'Same video', kind: 'video' })
  const agnes = await seedModel(page, b, { modelId: 'agnes-video-2.5', displayName: 'Same video', kind: 'video' })
  const hf = await seedModel(page, b, { modelId: 'bytedance/seedance-2.5', displayName: 'HF video', kind: 'video' })
  const flash = await seedModel(page, b, { modelId: 'agnes-video-2.5-flash', displayName: 'Flash video', kind: 'video' })
  const editor = await openScene(page)
  const provider = editor.getByLabel('Nhà cung cấp video')
  const model = editor.getByRole('combobox', { name: 'Model video', exact: true })
  await provider.selectOption(a)
  await expect(model.locator('option')).toHaveCount(2)
  await expect(model).toHaveValue(openai)
  await expect(model.locator(`option[value="${openai}"]`)).toContainText('Provider A')
  await model.selectOption(openai)
  await editor.getByLabel('Tên cảnh').fill('Mountain')
  await editor.getByLabel('Mô tả / hành động').fill('Camera moves over the mountains')
  const advanced = editor.locator('.project-advanced')
  await advanced.locator('summary').click()
  const json = advanced.locator('textarea')
  await json.fill(JSON.stringify({ size: '1920x1200', seconds: '19', allowTemporaryMedia: true, logoOverlays: [] }))
  await expect(editor.getByLabel('Độ phân giải')).toHaveValue('1920x1200')
  await provider.selectOption(b)
  await expect(model.locator('option')).toHaveCount(4)
  await model.selectOption(hf)
  expect(JSON.parse(await json.inputValue())).toMatchObject({ mode: 'text', duration: 5, allowTemporaryMedia: true })
  await model.selectOption(agnes)
  expect(JSON.parse(await json.inputValue())).toMatchObject({ size: '720P', seconds: '5', allowTemporaryMedia: true })
  expect(JSON.parse(await json.inputValue())).not.toHaveProperty('duration')
  await editor.getByRole('spinbutton', { name: 'Thời lượng' }).fill('30')
  await model.selectOption(flash)
  await expect(editor.getByRole('spinbutton', { name: 'Thời lượng' })).toHaveValue('30')
  await expect(editor.getByRole('spinbutton', { name: 'Thời lượng' })).toHaveAttribute('max', '12')
  await expect(editor.locator('.agnes-controls select').nth(1)).toBeDisabled()
  await editor.getByRole('spinbutton', { name: 'Thời lượng' }).fill('13')
  await editor.getByRole('button', { name: 'Lưu & xem trước prompt' }).click()
  await expect(editor.locator('.project-prompt-preview')).toHaveCount(0)
  await provider.selectOption(a)
  await model.selectOption(openai)
  expect(JSON.parse(await json.inputValue())).not.toHaveProperty('mode')
  await json.fill('{broken')
  await editor.getByRole('button', { name: 'Lưu & xem trước prompt' }).click()
  await expect(editor.locator('.project-prompt-preview')).toHaveCount(0)
  await json.fill('{}')
  await editor.getByLabel('Tỷ lệ khung hình').selectOption('9:16')
  await editor.getByLabel('Độ phân giải').selectOption('2160')
  await editor.getByRole('spinbutton', { name: 'Thời lượng' }).fill('17')
  await editor.getByRole('button', { name: 'Lưu & xem trước prompt' }).click()
  await expect(editor.locator('.project-prompt-preview')).toBeVisible()
  await editor.getByRole('spinbutton', { name: 'Thời lượng' }).fill('18')
  await expect(editor.locator('.project-prompt-preview')).toHaveCount(0)
  await editor.getByRole('button', { name: 'Lưu & xem trước prompt' }).click()
  await expect(editor.locator('.project-prompt-preview')).toBeVisible()
  const response = page.waitForResponse(response => /\/api\/scenes\/[^/]+\/generate$/.test(response.url()) && response.request().method() === 'POST')
  await editor.getByRole('button', { name: 'Tạo / thử lại phiên bản mới' }).click()
  const generated = await response
  expect(generated.status()).toBe(202)
  const { generation } = await generated.json()
  expect(generation.params).toMatchObject({ size: '2160x3840', seconds: '18' })
  await waitForGeneration(page, generation.id)
  await expect(editor.locator('.project-version-card')).toHaveCount(1)
})

test('disabled saved model remains selected with warning instead of replacement', async ({ page }) => {
  await signUpFresh(page)
  const provider = await seedProvider(page)
  const modelId = await seedModel(page, provider, { modelId: 'old-video', kind: 'video' })
  const project = (await (await page.request.post(`${BASE}/api/projects`, { data: { name: 'Unavailable model' } })).json()).project
  const scene = (await (await page.request.post(`${BASE}/api/projects/${project.id}/scenes`, { data: { title: 'Old scene', prompt: 'Old prompt', modelId, params: { size: '1920x1200', seconds: '19' } } })).json()).scene
  expect((await page.request.patch(`${BASE}/api/models/${modelId}`, { data: { enabled: false } })).ok()).toBe(true)
  await page.goto(`${BASE}/?page=studio&project=${project.id}`)
  await page.getByText('Unavailable model', { exact: true }).click()
  await page.getByRole('tab', { name: 'Cảnh video', exact: true }).click()
  await page.getByRole('button', { name: 'Sửa cảnh Old scene', exact: true }).click()
  const editor = page.locator('.project-scene-editor')
  await expect(editor.getByRole('alert')).toContainText('Model video đã lưu không còn khả dụng')
  await expect(editor.getByRole('combobox', { name: 'Model video', exact: true })).toHaveValue(scene.modelId)
  await editor.getByRole('button', { name: 'Lưu & xem trước prompt' }).click()
  await expect(editor.locator('.project-prompt-preview')).toHaveCount(0)
})
