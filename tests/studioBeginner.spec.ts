test('optional groups preserve image and scene values when collapsed and reopened', async ({ page }) => {
  await signUpFresh(page)
  const provider = await seedProvider(page)
  await seedModel(page, provider, { modelId: 'mock-image-model', kind: 'image' })
  const videoModel = await seedModel(page, provider, { modelId: 'mock-video-model', kind: 'video' })
  await page.goto(BASE)
  const projectId = await createMandatoryOnly(page)
  const characterResponse = await page.request.post(`${BASE}/api/projects/${projectId}/characters`, { data: { name: 'Lan', appearance: 'Áo xanh' } })
  expect(characterResponse.ok()).toBe(true)
  await page.reload()
  await page.getByRole('button', { name: /Dự án đầu tiên/ }).click()
  await expect(page.locator('.project-tab-panel')).toBeVisible()
  const composer = page.locator('.project-composer')
  const references = composer.locator('.studio-disclosure')
  await expect(references).toHaveJSProperty('open', false)
  await references.locator(':scope > summary').click()
  const advanced = references.locator('.project-advanced')
  await advanced.locator('summary').click()
  await advanced.locator('textarea').fill('{"seed":42}')
  await references.locator(':scope > summary').click()
  await expect(advanced.locator('textarea')).not.toBeVisible()
  await references.locator(':scope > summary').click()
  await expect(advanced.locator('textarea')).toHaveValue('{"seed":42}')
  await page.locator('.studio-start-guide').getByRole('button', { name: 'Tạo cảnh video đầu tiên', exact: true }).click()
  const editor = page.locator('.project-scene-editor')
  const extras = editor.locator('.studio-disclosure')
  await expect(extras).toHaveJSProperty('open', false)
  await extras.locator(':scope > summary').click()
  await editor.getByRole('textbox', { name: 'Bối cảnh', exact: true }).fill('Bờ biển lúc bình minh')
  await editor.getByRole('textbox', { name: 'Lời thoại', exact: true }).fill('Chào ngày mới')
  await extras.locator(':scope > summary').click()
  await expect(editor.getByRole('textbox', { name: 'Bối cảnh', exact: true })).not.toBeVisible()
  await extras.locator(':scope > summary').click()
  await expect(editor.getByRole('textbox', { name: 'Bối cảnh', exact: true })).toHaveValue('Bờ biển lúc bình minh')
  await expect(editor.getByRole('textbox', { name: 'Lời thoại', exact: true })).toHaveValue('Chào ngày mới')
  await editor.getByRole('combobox', { name: 'Một nhân vật nói', exact: true }).selectOption({ label: 'Lan' })
  await editor.getByLabel('Tên cảnh').fill('Bình minh')
  await editor.getByLabel('Mô tả / hành động').fill('Sóng nhẹ vỗ bờ')
  await editor.getByRole('button', { name: 'Cấu hình video', exact: true }).click()
  await editor.getByRole('combobox', { name: 'Model video', exact: true }).selectOption(videoModel)
  await editor.locator('xpath=ancestor::*[@role="dialog"][1]').getByRole('button', { name: 'Lưu & xem trước prompt' }).click()
  await expect(editor.locator('.project-prompt-preview')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Sửa cảnh Bình minh', exact: true }).click()
  await expect(page.locator('.project-scene-editor .studio-disclosure')).toHaveJSProperty('open', true)
  await expect(page.locator('.project-scene-editor').getByRole('textbox', { name: 'Bối cảnh', exact: true })).toHaveValue('Bờ biển lúc bình minh')
  const response = await page.request.get(`${BASE}/api/projects/${projectId}/scenes`)
  expect((await response.json()).scenes[0]).toMatchObject({ background: 'Bờ biển lúc bình minh', dialogue: 'Chào ngày mới' })
})

test('project language supports a required custom code', async ({ page }) => {
  await signUpFresh(page)
  await page.goto(BASE)
  await page.getByRole('button', { name: 'Tạo dự án', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Tạo dự án', exact: true })
  await dialog.getByLabel('Tên dự án').fill('Projet français')
  await dialog.getByRole('combobox', { name: 'Ngôn ngữ', exact: true }).selectOption('other')
  await expect(dialog.getByLabel('Mã ngôn ngữ')).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Lưu dự án' })).toBeDisabled()
  await dialog.getByLabel('Mã ngôn ngữ').fill('fr')
  const saved = page.waitForResponse(response => response.url().endsWith('/api/projects') && response.request().method() === 'POST')
  await dialog.getByRole('button', { name: 'Lưu dự án' }).click()
  expect((await (await saved).json()).project.language).toBe('fr')
  await page.locator('.studio-project-manage > summary').click()
  await page.getByRole('button', { name: 'Sửa dự án', exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Sửa dự án', exact: true })
  await expect(edit.getByRole('combobox', { name: 'Ngôn ngữ', exact: true })).toHaveValue('other')
  await expect(edit.getByLabel('Mã ngôn ngữ')).toHaveValue('fr')
})
