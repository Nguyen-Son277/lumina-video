import { expect, test, type Page } from '@playwright/test'
import { BASE, seedModel, seedProvider, signUpFresh, waitForGeneration } from './helpers/auth'

async function noOverflow(page: Page) {
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
}

async function createMandatoryOnly(page: Page, name = 'Dự án đầu tiên') {
  const create = page.getByRole('button', { name: 'Tạo dự án', exact: true })
  await expect(create).toHaveCount(1)
  await expect(page.locator('.studio-start-guide')).toHaveJSProperty('open', true)
  await expect(page.locator('.project-start-card')).toHaveCount(0)
  await page.locator('.studio-start-guide > summary').click()
  await expect(create).toBeVisible()
  await create.click()
  const dialog = page.getByRole('dialog', { name: 'Tạo dự án', exact: true })
  await expect(dialog.getByRole('button', { name: 'Lưu dự án' })).toBeDisabled()
  await expect(dialog.getByRole('combobox', { name: 'Ngôn ngữ', exact: true })).toHaveValue('vi')
  await dialog.getByLabel('Tên dự án').fill(name)
  const saved = page.waitForResponse(response => response.url().endsWith('/api/projects') && response.request().method() === 'POST')
  await dialog.getByRole('button', { name: 'Lưu dự án' }).click()
  const response = await saved
  expect(response.status()).toBe(201)
  const { project } = await response.json()
  expect(project).toMatchObject({ name, language: 'vi', description: '', style: '' })
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  await expect(page.locator('.project-tab-panel')).toBeVisible()
  return project.id as string
}

test('novice creates a project with mandatory fields only, then an image and a video', async ({ page }) => {
  await signUpFresh(page)
  const provider = await seedProvider(page)
  const imageModel = await seedModel(page, provider, { modelId: 'mock-image-model', kind: 'image' })
  const videoModel = await seedModel(page, provider, { modelId: 'mock-video-model', kind: 'video' })
  let generated = 0
  page.on('request', request => {
    if (request.method() === 'POST' && (/\/api\/generations$/.test(request.url()) || /\/api\/scenes\/[^/]+\/generate$/.test(request.url()))) generated++
  })
  await page.goto(BASE)
  const projectId = await createMandatoryOnly(page)
  expect(generated).toBe(0)
  const guide = page.locator('.studio-start-guide')
  await expect(guide).toHaveJSProperty('open', true)
  await expect(page.locator('.studio-project-manage')).toHaveJSProperty('open', false)
  await guide.getByRole('button', { name: 'Tạo ảnh đầu tiên', exact: true }).click()
  const composer = page.locator('.project-composer')
  await expect(composer.getByLabel('Mô tả ảnh')).toBeFocused()
  await expect(composer.locator('.studio-disclosure')).toHaveJSProperty('open', false)
  await composer.getByLabel('Mô tả ảnh').fill('Một ngôi nhà nhỏ giữa rừng thông')
  await composer.getByRole('combobox', { name: 'Model ảnh', exact: true }).selectOption(imageModel)
  const imageCreated = page.waitForResponse(response => response.url().endsWith('/api/generations') && response.request().method() === 'POST')
  await composer.getByRole('button', { name: 'Tạo ảnh', exact: true }).click()
  const imageResponse = await imageCreated
  expect(imageResponse.status()).toBe(202)
  const { generation: image } = await imageResponse.json()
  expect((await waitForGeneration(page, image.id)).status).toBe('succeeded')
  await expect(page.locator('.project-results .creation-card')).toHaveCount(1)

  // The guide remains available after the first result, even if it has collapsed.
  if (!await guide.evaluate(element => (element as HTMLDetailsElement).open)) await guide.locator('summary').click()
  await guide.getByRole('button', { name: 'Tạo cảnh video đầu tiên', exact: true }).click()
  const editor = page.locator('.project-scene-editor')
  await expect(editor).toBeVisible()
  await expect(editor.locator('.studio-disclosure')).toHaveJSProperty('open', false)
  await editor.getByLabel('Tên cảnh').fill('Rừng thông')
  await editor.getByLabel('Mô tả / hành động').fill('Máy quay tiến chậm qua rừng thông')
  await editor.getByRole('button', { name: 'Cấu hình video', exact: true }).click()
  await editor.getByRole('combobox', { name: 'Model video', exact: true }).selectOption(videoModel)
  const generate = editor.locator('xpath=ancestor::*[@role="dialog"][1]').getByRole('button', { name: 'Tạo / thử lại phiên bản mới' })
  await expect(generate).toBeDisabled()
  await editor.locator('xpath=ancestor::*[@role="dialog"][1]').getByRole('button', { name: 'Lưu cảnh', exact: true }).click()
  await expect(generate).toBeEnabled()
  await expect(editor.locator('.project-prompt-preview')).toHaveCount(0)
  const videoCreated = page.waitForResponse(response => /\/api\/scenes\/[^/]+\/generate$/.test(response.url()) && response.request().method() === 'POST')
  await generate.click()
  const videoResponse = await videoCreated
  expect(videoResponse.status()).toBe(202)
  const { generation: video } = await videoResponse.json()
  expect((await waitForGeneration(page, video.id)).status).toBe('succeeded')
  await expect(editor.getByRole('button', { name: 'Chọn phiên bản này' })).toBeEnabled({ timeout: 15_000 })
  expect(generated).toBe(2)
  const scenes = await page.request.get(`${BASE}/api/projects/${projectId}/scenes`)
  expect((await scenes.json()).scenes).toHaveLength(1)
})

for (const width of [1440, 1024, 390, 320]) {
  test(`beginner Studio fits ${width}px and supports keyboard tabs`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await signUpFresh(page)
    await page.goto(BASE)
    await expect(page.getByRole('heading', { name: 'Dự án sáng tạo' })).toBeVisible()
    await noOverflow(page)
    await createMandatoryOnly(page)
    await noOverflow(page)
    await page.screenshot({ path: `shots/studio-beginner-${width}.png`, fullPage: true })
    const tabs = page.getByRole('tablist', { name: 'Dự án sáng tạo' })
    const images = tabs.getByRole('tab', { name: 'Ảnh', exact: true })
    const characters = tabs.getByRole('tab', { name: 'Nhân vật', exact: true })
    await images.focus()
    await page.keyboard.press('ArrowRight')
    await expect(characters).toBeFocused()
    await expect(characters).toHaveAttribute('aria-selected', 'true')
    await expect(images).toHaveAttribute('tabindex', '-1')
    await page.keyboard.press('End')
    await expect(tabs.getByRole('tab', { name: 'Canvas', exact: true })).toBeFocused()
    await page.keyboard.press('Home')
    await expect(images).toBeFocused()
    await expect(images).toHaveAttribute('aria-selected', 'true')
    await page.keyboard.press('ArrowLeft')
    await expect(tabs.getByRole('tab', { name: 'Canvas', exact: true })).toBeFocused()
    await page.keyboard.press('Home')
    await page.locator('.studio-start-guide').getByRole('button', { name: 'Tạo cảnh video đầu tiên', exact: true }).click()
    await expect(page.locator('.project-scene-editor')).toBeVisible()
    await noOverflow(page)
    await expect.poll(() => page.locator('.project-scene-modal-body').evaluate(element => element.scrollWidth - element.clientWidth)).toBeLessThanOrEqual(1)
  })
}

