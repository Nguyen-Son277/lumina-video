import { expect, test, type Locator } from '@playwright/test'
import { BASE, seedProvider, signUpFresh } from './helpers/auth'
import { providerKeysCatalog as K } from '../src/i18n/catalogs/providerKeys'

async function verifyToggle(field: Locator, name: 'mật khẩu' | 'API key', value: string) {
  const input = field.locator('input')
  await expect(input).toHaveAttribute('type', 'password')
  await input.fill(value)
  const show = field.getByRole('button', { name: `Hiện ${name}`, exact: true })
  await expect(show).toHaveAttribute('type', 'button')
  await expect(show.locator('svg.lucide-eye')).toBeVisible()
  await expect(show).toHaveText('')
  const bounds = await show.boundingBox()
  expect(bounds?.width).toBeGreaterThanOrEqual(40)
  expect(bounds?.height).toBeGreaterThanOrEqual(40)
  await show.click()
  await expect(input).toHaveAttribute('type', 'text')
  await expect(input).toHaveValue(value)
  const hide = field.getByRole('button', { name: `Ẩn ${name}`, exact: true })
  await expect(hide).toHaveAttribute('aria-pressed', 'true')
  await expect(hide.locator('svg.lucide-eye-off')).toBeVisible()
  await hide.focus(); await hide.press('Enter')
  await expect(input).toHaveAttribute('type', 'password')
  await expect(input).toHaveValue(value)
}

test('login/register password visibility is reversible, accessible and resets on mode switch', async ({ page }) => {
  await page.goto(BASE)
  let requests = 0
  page.on('request', request => { if (request.method() === 'POST' && /\/api\/auth\/(login|register)$/.test(request.url())) requests++ })
  const field = page.locator('.auth-form .secret-field')
  await verifyToggle(field, 'mật khẩu', 'test-password-123')
  await expect(page.getByLabel('Mật khẩu', { exact: true })).toHaveCount(1)
  await field.getByRole('button', { name: 'Hiện mật khẩu', exact: true }).click()
  await page.getByRole('button', { name: 'Đăng ký ngay', exact: true }).click()
  await expect(field.locator('input')).toHaveAttribute('type', 'password')
  await expect(field.locator('input')).toHaveAttribute('autocomplete', 'new-password')
  await verifyToggle(field, 'mật khẩu', 'new-password-456')
  expect(requests).toBe(0)
  await page.locator('.auth-locale select').selectOption('en')
  await expect(field.getByRole('button', { name: 'Show password', exact: true })).toBeVisible()
  for (const width of [320, 390]) {
    await page.setViewportSize({ width, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
  }
  await field.locator('input').fill('')
  // Evidence goes to gitignored test-results so a normal E2E run never dirties shots/.
  await page.screenshot({ path: 'test-results/password-eye-mobile.png', fullPage: true })
})

test('provider API key show/hide preserves submission and resets when dialog reopens', async ({ page }) => {
  await signUpFresh(page)
  await page.goto(`${BASE}/?page=settings`)
  await page.getByRole('button', { name: 'Thêm provider', exact: true }).first().click()
  const dialog = page.getByRole('dialog', { name: 'Thêm provider' })
  const field = dialog.locator('.secret-field')
  await verifyToggle(field, 'API key', 'sk-visibility-test-1234')
  await expect(dialog.getByLabel('API key', { exact: true })).toHaveCount(1)
  await field.getByRole('button', { name: 'Hiện API key', exact: true }).click()
  await dialog.getByRole('button', { name: 'Hủy', exact: true }).click()
  await page.getByRole('button', { name: 'Thêm provider', exact: true }).first().click()
  await expect(field.locator('input')).toHaveAttribute('type', 'password')
  await expect(field.locator('input')).toHaveValue('')
  await dialog.getByPlaceholder('Ví dụ: Production gateway').fill('Visibility provider')
  await dialog.getByPlaceholder('https://api.example.com/v1').fill('https://e2e.mock.test/v1')
  await field.locator('input').fill('sk-visibility-test-1234')
  await field.getByRole('button', { name: 'Hiện API key', exact: true }).click()
  const request = page.waitForRequest(request => request.method() === 'POST' && request.url().endsWith('/api/providers'))
  await dialog.getByRole('button', { name: 'Lưu provider', exact: true }).click()
  expect((await request).postDataJSON().apiKey).toBe('sk-visibility-test-1234')
  await expect(dialog).toHaveCount(0)
})

test('add/edit credential visibility never retrieves old secret and remains usable on mobile', async ({ page }) => {
  await signUpFresh(page)
  await seedProvider(page, { name: 'Secret provider', apiKey: 'sk-old-hidden-1234' })
  await page.goto(`${BASE}/?page=settings`)
  const item = page.locator('.provider-item').filter({ hasText: 'Secret provider' })
  await item.getByRole('button', { name: K.keysAria.vi.replace('{name}', 'Secret provider') }).click()
  const panel = item.locator('.provider-credentials-panel')
  await panel.getByRole('button', { name: K.addKey.vi, exact: true }).click()
  const add = page.getByRole('dialog', { name: K.addKeyTitle.vi })
  await verifyToggle(add.locator('.secret-field'), 'API key', 'sk-new-visible-5678')
  await add.getByLabel(K.labelField.vi).fill('New key')
  await add.getByRole('button', { name: K.saveKey.vi }).click()
  await expect(add).toHaveCount(0)
  await panel.getByRole('button', { name: K.editKeyAria.vi.replace('{label}', 'Key mặc định') }).click()
  const edit = page.getByRole('dialog', { name: K.editKeyTitle.vi })
  const field = edit.locator('.secret-field')
  await expect(field.locator('input')).toHaveValue('')
  await field.getByRole('button', { name: 'Hiện API key', exact: true }).click()
  await expect(field.locator('input')).toHaveValue('')
  expect(await page.content()).not.toContain('sk-old-hidden-1234')
  await field.getByRole('button', { name: 'Ẩn API key', exact: true }).click()
  await verifyToggle(field, 'API key', 'sk-replacement-test-9012')
  for (const width of [320, 390]) {
    await page.setViewportSize({ width, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
  }
})
