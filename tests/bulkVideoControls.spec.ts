import { test, expect } from '@playwright/test'
import { BASE, seedProvider, seedModel, signUpFresh, waitForGeneration } from './helpers/auth'

test('bulk provider settings persist without generating and are used by scene generation', async ({ page }) => {
  await signUpFresh(page)
  const a = await seedProvider(page, { name: 'Bulk Provider A' })
  const b = await seedProvider(page, { name: 'Bulk Provider B' })
  const openai = await seedModel(page, a, { modelId: 'bulk-video', displayName: 'Same model', kind: 'video' })
  const flash = await seedModel(page, b, { modelId: 'agnes-video-2.5-flash', displayName: 'Same model', kind: 'video' })
  const hf = await seedModel(page, b, { modelId: 'bytedance/seedance-2.5', displayName: 'HF video', kind: 'video' })
  const project = (await (await page.request.post(`${BASE}/api/projects`, { data: { name: 'Bulk video regression' } })).json()).project
  const scene = (await (await page.request.post(`${BASE}/api/projects/${project.id}/scenes`, { data: { title: 'Mountain', prompt: 'A mountain panorama', modelId: hf, params: { mode: 'text', duration: 5 } } })).json()).scene
  await page.goto(`${BASE}/?page=studio&project=${project.id}`)
  await page.getByText('Bulk video regression', { exact: true }).click()
  await page.getByRole('tab', { name: 'Cảnh video', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Chọn cảnh Mountain', exact: true }).check()
  const opener = page.getByRole('button', { name: 'Cấu hình video hàng loạt', exact: true })
  await opener.click()
  const modal = page.getByRole('dialog', { name: 'Cấu hình video hàng loạt', exact: true }).and(page.locator('.project-scene-modal'))
  const bulk = modal.locator('.project-bulk-video-settings')
  const provider = bulk.getByLabel('Nhà cung cấp video')
  const model = bulk.getByRole('combobox', { name: 'Model video', exact: true })
  await provider.selectOption(b)
  await expect(model.locator('option')).toHaveCount(3)
  await model.selectOption(flash)
  await expect(bulk.getByRole('spinbutton', { name: 'Thời lượng' })).toHaveAttribute('max', '12')
  await expect(bulk.locator('.agnes-controls select').nth(1)).toBeDisabled()
  await model.selectOption(hf)
  await expect(bulk.getByRole('spinbutton', { name: 'Thời lượng' })).toHaveValue('5')
  await provider.selectOption(a)
  await expect(model).toHaveValue(openai)
  await expect(model.locator('option')).toHaveCount(2)
  await expect(model.locator(`option[value="${openai}"]`)).toContainText('Bulk Provider A')
  await bulk.locator('.project-advanced summary').click()
  const json = bulk.locator('.project-advanced textarea')
  await json.fill('{broken')
  await expect(bulk.getByRole('button', { name: 'Áp dụng model và cấu hình' })).toBeDisabled()
  await json.fill('{}')
  await bulk.getByRole('spinbutton', { name: 'Thời lượng' }).fill('3')
  await expect(bulk.getByRole('button', { name: 'Áp dụng model và cấu hình' })).toBeDisabled()
  await bulk.getByLabel('Tỷ lệ khung hình').selectOption('9:16')
  await bulk.getByLabel('Độ phân giải').selectOption('1080')
  await bulk.getByRole('spinbutton', { name: 'Thời lượng' }).fill('17')
  const saved = page.waitForResponse(r => r.url().endsWith(`/projects/${project.id}/scenes/bulk`) && r.request().method() === 'POST')
  await bulk.getByRole('button', { name: 'Áp dụng model và cấu hình' }).click()
  const response = await saved
  expect(response.ok()).toBe(true)
  expect((await response.json()).scenes[0]).toMatchObject({ modelId: openai, autoGenerate: false, params: { size: '1080x1920', seconds: '17' } })
  const before = await (await page.request.get(`${BASE}/api/generations?projectId=${project.id}`)).json()
  expect(before.generations).toHaveLength(0)
  await page.reload()
  await page.getByRole('tab', { name: 'Cảnh video', exact: true }).click()
  const persisted = (await (await page.request.get(`${BASE}/api/projects/${project.id}/scenes`)).json()).scenes[0]
  expect(persisted.params).toMatchObject({ size: '1080x1920', seconds: '17' })
  expect(persisted.params).not.toHaveProperty('duration')
  const generated = await page.request.post(`${BASE}/api/scenes/${scene.id}/generate`, { data: { idempotencyKey: crypto.randomUUID() } })
  expect(generated.status()).toBe(202)
  const { generation } = await generated.json()
  expect(generation.params).toMatchObject({ size: '1080x1920', seconds: '17' })
  await waitForGeneration(page, generation.id)
})
