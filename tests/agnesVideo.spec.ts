import { expect, test } from '@playwright/test'
import { BASE, signUpFresh, seedModel, seedProvider } from './helpers/auth'

test.beforeEach(async ({ page }) => { await signUpFresh(page) })
test('Agnes Flash classified automatically and quick video sends 720P mode and ratio', async ({ page }) => {
  const provider = await seedProvider(page)
  await seedModel(page, provider, { modelId: 'agnes-video-2.5-flash', kind: 'video', displayName: 'Agnes Flash' })
  await page.goto(`${BASE}/?page=quick`)
  await page.locator('.mode-tabs button').nth(1).click()
  await expect(page.locator('.agnes-controls')).toBeVisible()
  await expect(page.getByLabel('Độ phân giải', { exact: true })).toHaveValue('720P')
  await page.getByRole('combobox', { name: 'Tỷ lệ khung hình', exact: true }).selectOption('9:16')
  await page.getByPlaceholder('Mô tả điều bạn muốn tạo...').fill('Một chú mèo chạy')
  const request = page.waitForRequest(req => req.method() === 'POST' && req.url().endsWith('/api/generations'))
  await page.locator('.generate-button').click()
  const params = (await request).postDataJSON().params
  expect(params).toMatchObject({ mode: 'text', size: '720P', seconds: '5', aspectRatio: '9:16', useCharacterReference: false, n: 1 })
  await page.getByRole('button', { name: 'API & Models', exact: true }).click()
  await page.getByRole('button', { name: /Model catalog/ }).click()
  await expect(page.getByLabel('Kiểu API video')).toHaveValue('agnes')
  await page.getByLabel('Kiểu API video').selectOption('openai')
  await expect(page.getByLabel('Kiểu API video')).toHaveValue('openai')
  await page.reload()
  await page.getByRole('button', { name: /Model catalog/ }).click()
  await expect(page.getByLabel('Kiểu API video')).toHaveValue('openai')
})
test('Agnes media mode fields and mode switching do not leak previous inputs', async ({ page }) => {
  const provider = await seedProvider(page)
  await seedModel(page, provider, { modelId: 'agnes-video-2.5-flash', kind: 'video' })
  await page.goto(`${BASE}/?page=quick`)
  await page.locator('.mode-tabs button').nth(1).click()
  await page.getByLabel('Chế độ tạo Agnes').selectOption('keyframe')
  await page.getByLabel('URL khung đầu', { exact: true }).fill('https://example.com/first.png')
  await page.getByLabel('Chế độ tạo Agnes').selectOption('reference')
  await expect(page.getByLabel('URL khung đầu', { exact: true })).toHaveCount(0)
  await page.getByLabel('URL ảnh (mỗi dòng một URL, Flash: tối đa 5)').fill('https://example.com/character.png')
  await page.getByLabel('Chế độ tạo Agnes').selectOption('text')
  await expect(page.locator('.agnes-controls textarea')).toHaveCount(0)
})
test('Agnes scene controls store the same parameters in Studio', async ({ page }) => {
  const provider = await seedProvider(page)
  const model = await seedModel(page, provider, { modelId: 'agnes-video-2.5-flash', kind: 'video' })
  await page.goto(BASE)
  await page.getByRole('button', { name: 'Tạo dự án', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Tạo dự án' })
  await dialog.getByLabel('Tên dự án').fill('Agnes project')
  await dialog.getByRole('button', { name: 'Lưu dự án' }).click()
  await expect(page.locator('.project-tab-panel')).toBeVisible()
  await page.getByRole('tab', { name: 'Cảnh video', exact: true }).click()
  await page.getByRole('button', { name: 'Thêm cảnh', exact: true }).click()
  const editor = page.locator('.project-scene-editor')
  await editor.getByLabel('Tên cảnh').fill('Agnes scene')
  await editor.getByLabel('Mô tả / hành động').fill('A cat runs')
  await editor.getByRole('combobox', { name: 'Model video', exact: true }).selectOption(model)
  await expect(editor.locator('.agnes-controls')).toBeVisible()
  await editor.getByRole('combobox', { name: 'Tỷ lệ khung hình', exact: true }).selectOption('9:16')
  await editor.getByRole('button', { name: 'Lưu & xem trước prompt' }).click()
  const request = page.waitForResponse(r => /\/api\/scenes\/[^/]+\/generate$/.test(r.url()) && r.request().method() === 'POST')
  await editor.getByRole('button', { name: 'Tạo / thử lại phiên bản mới' }).click()
  const response = await request
  expect(response.status()).toBe(202)
  expect((await response.json()).generation.params).toMatchObject({ mode: 'text', size: '720P', seconds: '5', aspectRatio: '9:16' })
})

