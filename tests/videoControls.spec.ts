import { expect, test } from '@playwright/test'
import { BASE, seedModel, seedProvider, signUpFresh, waitForGeneration } from './helpers/auth'

test('quick video controls validate seconds and preserve size/seconds payload', async ({ page }) => {
  await signUpFresh(page)
  const provider = await seedProvider(page)
  await seedModel(page, provider, { modelId: 'video', kind: 'video' })
  await page.goto(`${BASE}/?page=quick`)
  await page.getByRole('button', { name: 'Phiên mới', exact: true }).first().click()
  await page.locator('.entity-options__consent input').uncheck()
  await page.locator('.mode-tabs button').nth(1).click()
  await page.getByRole('button', { name: 'Cấu hình', exact: true }).click()
  const duration = page.getByRole('spinbutton', { name: 'Thời lượng' })
  await expect(duration).toHaveAttribute('min', '4')
  await expect(duration).toHaveAttribute('max', '30')
  await duration.fill('31')
  await expect(page.getByRole('button', { name: 'Lưu cấu hình', exact: true })).toBeDisabled()
  await expect(page.locator('.generate-button')).toBeDisabled()
  await expect(page.getByRole('alert')).toContainText('Nhập số giây nguyên')
  await duration.fill('17')
  await page.getByRole('combobox', { name: 'Tỷ lệ khung hình', exact: true }).selectOption('9:16')
  const resolution = page.getByRole('combobox', { name: 'Độ phân giải', exact: true })
  await expect(resolution.locator('option')).toHaveText(['480p', '720p', '1K (1080p)', '2K (1440p)', '4K (2160p)'])
  await resolution.selectOption('2160')
  await page.getByRole('button', { name: 'Lưu cấu hình', exact: true }).click()
  await page.getByPlaceholder('Mô tả điều bạn muốn tạo...').fill('A mountain at sunrise')
  const request = page.waitForRequest(req => /\/api\/generations$/.test(req.url()) && req.method() === 'POST')
  await page.locator('.generate-button').click()
  expect((await request).postDataJSON().params).toMatchObject({ size: '2160x3840', seconds: '17' })
})

test('editing historical video preserves custom dimensions and duration', async ({ page }) => {
  await signUpFresh(page)
  const provider = await seedProvider(page)
  const modelId = await seedModel(page, provider, { modelId: 'video', kind: 'video' })
  const response = await page.request.post(`${BASE}/api/quick-sessions`, { data: { title: 'Legacy video' } })
  const { session } = await response.json()
  const created = await page.request.post(`${BASE}/api/generations`, { data: { modelId, prompt: 'Legacy composition', quickSessionId: session.id, params: { size: '1920x1200', seconds: '19' } } })
  expect(created.status()).toBe(202)
  await waitForGeneration(page, (await created.json()).generation.id)
  await page.goto(`${BASE}/?page=quick&session=${session.id}`)
  await page.locator('.mode-tabs button').nth(1).click()
  await page.getByRole('button', { name: 'Sửa mô tả' }).first().click()
  await page.getByRole('button', { name: 'Cấu hình', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Thời lượng' })).toHaveValue('19')
  await page.getByRole('button', { name: 'Lưu cấu hình', exact: true }).click()
  await page.locator('.entity-options__consent input').uncheck()
  await page.getByRole('button', { name: 'Cấu hình', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Tỷ lệ khung hình', exact: true })).toHaveValue('1920x1200')
  await expect(page.getByRole('combobox', { name: 'Độ phân giải', exact: true })).toHaveValue('1920x1200')
  await page.getByRole('button', { name: 'Lưu cấu hình', exact: true }).click()
  const request = page.waitForRequest(req => /\/api\/generations$/.test(req.url()) && req.method() === 'POST')
  await page.locator('.generate-button').click()
  expect((await request).postDataJSON().params).toMatchObject({ size: '1920x1200', seconds: '19' })
})

test('Agnes duration changes range and Flash locks resolution', async ({ page }) => {
  await signUpFresh(page)
  const provider = await seedProvider(page)
  const standard = await seedModel(page, provider, { modelId: 'agnes-video-2.5', displayName: 'Agnes', kind: 'video' })
  const flash = await seedModel(page, provider, { modelId: 'agnes-video-2.5-flash', displayName: 'Flash', kind: 'video' })
  await page.goto(`${BASE}/?page=quick`)
  await page.getByRole('button', { name: 'Phiên mới', exact: true }).first().click()
  await page.locator('.mode-tabs button').nth(1).click()
  await page.getByRole('button', { name: 'Cấu hình', exact: true }).click()
  await page.getByRole('combobox', { name: 'Model video', exact: true }).selectOption(standard)
  const duration = page.getByRole('spinbutton', { name: 'Thời lượng' })
  await expect(duration).toHaveAttribute('max', '30')
  await duration.fill('30')
  await page.getByRole('combobox', { name: 'Model video', exact: true }).selectOption(flash)
  await expect(duration).toHaveAttribute('max', '12')
  await duration.fill('13')
  await expect(page.getByRole('button', { name: 'Lưu cấu hình', exact: true })).toBeDisabled()
  await expect(page.locator('.generate-button')).toBeDisabled()
  await duration.fill('12')
  await page.getByRole('button', { name: 'Lưu cấu hình', exact: true }).click()
  await page.getByRole('button', { name: 'Cấu hình', exact: true }).click()
  const savedDuration = page.getByRole('spinbutton', { name: 'Thời lượng' })
  await expect(savedDuration).toHaveValue('12')
  await expect(savedDuration).toHaveAttribute('max', '12')
  const resolution = page.locator('.agnes-controls select').nth(1)
  await expect(resolution).toBeDisabled()
  await expect(resolution).toHaveValue('720P')
  await page.getByRole('button', { name: 'Lưu cấu hình', exact: true }).click()
  await page.getByPlaceholder('Mô tả điều bạn muốn tạo...').fill('A mountain at sunrise')
  await expect(page.locator('.generate-button')).toBeEnabled()
})
